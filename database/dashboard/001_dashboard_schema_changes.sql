CREATE TABLE IF NOT EXISTS dashboard_preference (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    client_id          bigint NOT NULL,
    user_id            bigint NOT NULL,
    configuration_json jsonb NOT NULL,
    updated_on         timestamp without time zone NOT NULL,
    CONSTRAINT pk_dashboard_preference PRIMARY KEY (id),
    CONSTRAINT fk_dashboard_preference_client_client_id FOREIGN KEY (client_id) REFERENCES client(id) ON DELETE CASCADE,
    CONSTRAINT fk_dashboard_preference_user_user_id FOREIGN KEY (user_id) REFERENCES "user"(id) ON DELETE CASCADE
);
